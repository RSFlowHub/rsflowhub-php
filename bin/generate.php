<?php

declare(strict_types=1);

/**
 * Regenerates the SDK's typed layer from the live OpenAPI document:
 *
 *   php bin/generate.php                                   # https://rsflowhub.com/api/v1/openapi.json
 *   php bin/generate.php http://localhost/api/v1/openapi.json
 *   php bin/generate.php path/to/openapi.json
 *
 * Writes (never edit these by hand):
 *   src/Generated/Operations.php   resource => method => [HTTP method, path]
 *   src/Resources/*.php            @method docblocks for IDE autocomplete
 *   src/RSFlowHub.php              the <generated-resources> @property block
 *   docs/ENDPOINTS.md              reference table of every method
 *
 * The SDK works without running this (see src/Operations.php); it only adds
 * autocomplete and docs. The "Sync with API" GitHub workflow runs it weekly.
 */

require __DIR__ . '/../src/Operations.php';

use RSFlowHub\Operations;

$root = dirname(__DIR__);
$source = $argv[1] ?? (getenv('RSFLOWHUB_SPEC_URL') ?: 'https://rsflowhub.com/api/v1/openapi.json');

$raw = @file_get_contents($source, false, stream_context_create([
    'http' => ['timeout' => 30, 'header' => "Accept: application/json\r\nUser-Agent: rsflowhub-php-generator\r\n"],
]));
if ($raw === false) {
    fwrite(STDERR, "Could not read the OpenAPI document from {$source}\n");
    exit(1);
}
$spec = json_decode($raw, true);
if (! is_array($spec) || ! isset($spec['openapi'], $spec['paths'])) {
    fwrite(STDERR, "{$source} is not an OpenAPI document.\n");
    exit(1);
}

$map = Operations::fromSpec($spec);
if (! $map) {
    fwrite(STDERR, "No operations with x-rsflowhub-sdk found.\n");
    exit(1);
}

/** @var array<string, array<string, array{http: string, path: string, op: array}>> $ops */
$ops = [];
foreach ($spec['paths'] as $path => $operations) {
    foreach ($operations as $httpMethod => $op) {
        $sdk = $op['x-rsflowhub-sdk'] ?? null;
        if (is_array($sdk)) {
            $ops[$sdk['resource']][$sdk['method']] = ['http' => strtoupper($httpMethod), 'path' => $path, 'op' => $op];
        }
    }
}
ksort($ops);
foreach ($ops as &$methods) {
    ksort($methods);
}
unset($methods);

// 1. Operation map ---------------------------------------------------------
$lines = ["<?php", "", "// Generated by bin/generate.php from the RSFlowHub OpenAPI document. Do not edit.", "", "return ["];
foreach ($ops as $resource => $methods) {
    $lines[] = "    '{$resource}' => [";
    foreach ($methods as $method => $o) {
        $lines[] = "        '{$method}' => ['{$o['http']}', '{$o['path']}'],";
    }
    $lines[] = "    ],";
}
$lines[] = "];";
file_put_contents("{$root}/src/Generated/Operations.php", implode("\n", $lines) . "\n");

// 2. Resource classes with @method docblocks ---------------------------------
$phpType = function (array $schema) use (&$phpType): string {
    return match ($schema['type'] ?? null) {
        'string' => 'string',
        'integer' => 'int',
        'number' => 'float',
        'boolean' => 'bool',
        'array' => 'list<' . (isset($schema['items']['type']) ? $phpType($schema['items']) : 'mixed') . '>',
        'object' => 'array<string, mixed>',
        default => 'mixed',
    } . (! empty($schema['nullable']) ? '|null' : '');
};

$bodySchema = function (array $op): ?array {
    foreach (($op['requestBody']['content'] ?? []) as $content) {
        return $content['schema'] ?? null;
    }
    return null;
};

$glob = glob("{$root}/src/Resources/*.php") ?: [];
foreach ($glob as $file) {
    unlink($file);
}

$titles = [];
foreach ($ops as $resource => $methods) {
    $class = ucfirst($resource);
    $titles[$resource] = (string) (reset($methods)['op']['tags'][0] ?? $class);
    $doc = [];

    foreach ($methods as $method => $o) {
        $op = $o['op'];
        $args = [];
        foreach ($op['parameters'] ?? [] as $p) {
            if (($p['in'] ?? '') === 'path') {
                $args[] = 'int|string $' . lcfirst(str_replace('_', '', ucwords($p['name'], '_')));
            }
        }

        $fields = [];
        $schema = $bodySchema($op);
        if ($schema) {
            $required = $schema['required'] ?? [];
            foreach ((array) ($schema['properties'] ?? []) as $name => $prop) {
                $type = (($prop['format'] ?? null) === 'binary') ? 'resource|\\SplFileInfo' : $phpType((array) $prop);
                $fields[] = $name . (in_array($name, $required, true) ? '' : '?') . ': ' . $type;
            }
        } else {
            foreach ($op['parameters'] ?? [] as $p) {
                if (($p['in'] ?? '') === 'query') {
                    $fields[] = $p['name'] . (empty($p['required']) ? '?' : '') . ': ' . $phpType((array) ($p['schema'] ?? []));
                }
            }
        }
        if ($fields) {
            $args[] = 'array{' . implode(', ', $fields) . '} $params' . (! empty($schema['required']) ? '' : ' = []');
        } else {
            $args[] = 'array<string, mixed> $params = []';
        }

        $summary = trim((string) ($op['summary'] ?? ''));
        $doc[] = " * @method \\RSFlowHub\\Response {$method}(" . implode(', ', $args) . ") {$summary}. {$o['http']} {$o['path']}";
    }

    $title = $titles[$resource];
    $php = <<<PHP
<?php

declare(strict_types=1);

namespace RSFlowHub\\Resources;

use RSFlowHub\\Resource;

/**
 * {$title}. Generated by bin/generate.php from the RSFlowHub OpenAPI document. Do not edit.
 *
 * Methods not listed here still work (see RSFlowHub\\Operations).
 *

PHP;
    $php .= implode("\n", $doc) . "\n */\nfinal class {$class} extends Resource\n{\n}\n";
    file_put_contents("{$root}/src/Resources/{$class}.php", $php);
}

// 3. Client @property block ------------------------------------------------
$clientFile = "{$root}/src/RSFlowHub.php";
$client = file_get_contents($clientFile);
$props = [];
foreach (array_keys($ops) as $resource) {
    $props[] = " * @property-read Resources\\" . ucfirst($resource) . " \${$resource} {$titles[$resource]}";
}
$client = preg_replace(
    '/( \* <generated-resources>\n).*?( \* <\/generated-resources>)/s',
    '$1' . implode("\n", $props) . "\n" . '$2',
    $client,
    1
);
file_put_contents($clientFile, $client);

// 4. Reference docs ----------------------------------------------------------
$md = ["# RSFlowHub PHP SDK: method reference", "", "Generated by `bin/generate.php` from the [RSFlowHub OpenAPI document](https://rsflowhub.com/api/v1/openapi.json). Do not edit.", ""];
foreach ($ops as $resource => $methods) {
    $md[] = "## `\$client->{$resource}`: {$titles[$resource]}";
    $md[] = "";
    $md[] = "| Method | HTTP | Description | Credits |";
    $md[] = "| --- | --- | --- | --- |";
    foreach ($methods as $method => $o) {
        $credits = $o['op']['x-rsflowhub-credits']['base_credits'] ?? null;
        $desc = str_replace('|', '\\|', (string) ($o['op']['description'] ?? $o['op']['summary'] ?? ''));
        $md[] = "| `{$method}()` | `{$o['http']} {$o['path']}` | {$desc} | " . ($credits === null ? '-' : "from {$credits}") . " |";
    }
    $md[] = "";
}
@mkdir("{$root}/docs");
file_put_contents("{$root}/docs/ENDPOINTS.md", implode("\n", $md));

$count = array_sum(array_map('count', $ops));
echo "Generated {$count} methods in " . count($ops) . " resources from {$source}\n";
